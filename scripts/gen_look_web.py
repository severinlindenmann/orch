#!/usr/bin/env python3
"""Generate relay/web/look-data.js and publish/web/look-data.js from contracts/look.json + contracts/look/icons.
Icons are stored as element lists (tag + attributes) so the browser builds them with createElementNS, never from markup."""
import json, re, sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parent.parent
look = json.loads((root / "contracts/look.json").read_text())
icons = {}
for i in look["icons"]:
    tree = ET.parse(root / "contracts/look/icons" / f"{i['id']}.svg").getroot()
    els = []
    for e in tree:
        tag = re.sub(r"^\{.*\}", "", e.tag)
        assert tag in {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}, (i["id"], tag)
        els.append([tag, dict(e.attrib)])
    icons[i["id"]] = els
data = {
    "badge": look["badge"],
    "categories": look["categories"],
    "colors": look["colors"],
    "icons": [{"id": i["id"], "category": i["category"], "label": i["label"], "keywords": i["keywords"]} for i in look["icons"]],
    "drawings": icons,
}
js = "// Generated by scripts/gen_look_web.py from contracts/look.json. Do not edit.\nwindow.ORCH_LOOK_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n"
for d in ("relay", "publish"):
    (root / d / "web" / "look-data.js").write_text(js)
print("ok", len(js))

import shutil
shutil.copyfile(root / "publish/web/look.js", root / "relay/web/look.js")

# One script for the admin portals: data + look.js + look-admin.js (served as /admin/look.js)
for d in ("relay", "publish"):
    parts = [(root / d / "web" / "look-data.js").read_text(), (root / "publish/web/look.js").read_text(), (root / "publish/web/look-admin.js").read_text()]
    (root / d / "web" / "look-bundle.js").write_text("\n".join(parts))
shutil.copyfile(root / "publish/web/look.css", root / "relay/web/look.css")
shutil.copyfile(root / "publish/web/look-admin.js", root / "relay/web/look-admin.js")
