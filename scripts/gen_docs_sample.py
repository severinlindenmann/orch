"""Generate workspace/src/orch_ui/static/samples/docs-sample.js: every Documentation page orch ships (orch.docs.collect
over the shipped add-ons, sync shown as off) plus demo live facts, for the gallery entry and the mockup page.
Run it after any change to a docs.json:  python3 scripts/gen_docs_sample.py   (`--check` exits 1 when out of date)."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "workspace" / "src"))
OUT = ROOT / "workspace" / "src" / "orch_ui" / "static" / "samples" / "docs-sample.js"

LIVE = {
    "read": "10:31",
    "rows": {
        "relay": {"label": "Relay", "value": "Connected to relay.example.org", "short": "Connected", "tone": "done", "note": "as Demo · 1 phone paired"},
        "phone": {"label": "Phone", "value": "Questions go to your phone until 10:50", "tone": "done", "note": ""},
        "publish": {"label": "Publish", "value": "Connected", "tone": "done", "note": "may share apps and files"},
        "helper-limit": {"label": "Helper limit", "value": "3 at once", "tone": "", "note": "2 working now"},
        "reviewer": {"label": "Reviewer", "value": "Off", "tone": "off", "note": "only you move tickets to Done"},
        "addons": {"label": "Add-ons", "value": "10 on, 1 off", "tone": "", "note": ""},
    },
}


def build() -> dict:
    from orch import addons, docs

    rows = []
    for f in sorted((ROOT / "workspace" / "src" / "orch" / "builtin").glob("*/orch-addon.toml")) + sorted(
        (ROOT / "workspace-addons").glob("*/src/*/orch-addon.toml")
    ):
        m = addons.parse_manifest(f, core="builtin" in f.parts)
        rows.append({"name": m["name"], "active": m["name"] != "sync", "running": m["background"],
                     "background": m["background"], "docs_pages": m.get("docs_pages") or []})
    return {**docs.collect(rows), "live": LIVE}


def render() -> str:
    return ("/* Generated by scripts/gen_docs_sample.py from every shipped docs.json: do not edit. */\n"
            "window.DOCS_SAMPLE = " + json.dumps(build(), indent=1, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print("ok", OUT.relative_to(ROOT))
