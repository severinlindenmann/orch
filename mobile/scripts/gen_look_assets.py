#!/usr/bin/env python3
"""Generate the workspace icon image sets from contracts/look/icons (template images, vector data preserved).

Run from anywhere: python3 mobile/scripts/gen_look_assets.py. Also writes OrchMobile/LookData.swift (ids, labels, palette).
Source of truth: contracts/look.json + contracts/look/icons/*.svg (Lucide, ISC licence, contracts/look/LICENSE-lucide.txt).
"""
import json, pathlib, shutil

root = pathlib.Path(__file__).resolve().parents[2]
look = json.loads((root / "contracts/look.json").read_text())
cat = root / "mobile/OrchMobile/Assets.xcassets/WorkspaceIcons"
if cat.exists():
    shutil.rmtree(cat)
cat.mkdir(parents=True)
(cat / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": False}}, indent=2) + "\n")
for i in look["icons"]:
    d = cat / f"look-{i['id']}.imageset"
    d.mkdir()
    shutil.copy(root / f"contracts/look/icons/{i['id']}.svg", d / f"{i['id']}.svg")
    (d / "Contents.json").write_text(json.dumps({
        "images": [{"filename": f"{i['id']}.svg", "idiom": "universal"}],
        "info": {"author": "xcode", "version": 1},
        "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
    }, indent=2) + "\n")
(cat.parent.parent / "LookData.swift").write_text(
    "// Generated by mobile/scripts/gen_look_assets.py from contracts/look.json. Do not edit.\n"
    "enum LookData {\n"
    "    /// Colour tokens in contract order (the order picks the Automatic colour): id, dark tone hex, light tone hex.\n"
    "    static let colors: [(id: String, dark: UInt32, light: UInt32)] = [\n"
    + "".join(f'        ("{c["id"]}", 0x{c["dark"][1:]}, 0x{c["light"][1:]}),\n' for c in look["colors"])
    + "    ]\n    static let iconIds: Set<String> = [\n"
    + "".join(f'        "{i["id"]}",\n' for i in look["icons"]) + "    ]\n}\n")
print(len(look["icons"]), "icons,", len(look["colors"]), "colours")
